function getWordById(id) {
  return WORDS.find((w) => w.id === id);
}

function getTopicById(id) {
  return TOPICS.find((t) => t.id === id);
}

function wordsForTopic(topicId) {
  const topic = getTopicById(topicId);
  if (!topic) return [...WORDS];
  return topic.wordIds.map(getWordById).filter(Boolean);
}

/**
 * 相反位置：學習頁成對出現（左邊固定「大／多／長…」邊）
 * [leftId, rightId]
 */
const OPPOSITE_PAIRS = [
  ['da_big', 'xiao_small'],
  ['duo', 'shao'],
  ['chang_long', 'duan_short'],
  ['gao_tall', 'ai_short_height'],
  ['shang', 'xia'],
  ['qian_front', 'hou_back'],
  ['zuo_left', 'you_right'],
  ['limian', 'waimian'],
];

/** @returns {{ left: object, right: object }[]} */
function oppositePairWords(enabledIds = null) {
  const enabled = enabledIds && enabledIds.length ? new Set(enabledIds) : null;
  return OPPOSITE_PAIRS.map(([leftId, rightId]) => {
    const left = getWordById(leftId);
    const right = getWordById(rightId);
    if (!left || !right) return null;
    if (enabled && (!enabled.has(left.id) || !enabled.has(right.id))) return null;
    return { left, right };
  }).filter(Boolean);
}

/** 攞某個字嘅相反詞（無就 null） */
function getOppositeWord(wordId) {
  for (const [a, b] of OPPOSITE_PAIRS) {
    if (a === wordId) return getWordById(b) || null;
    if (b === wordId) return getWordById(a) || null;
  }
  return null;
}

/** 開發時檢查：唔好有重複 id（例如屋同五撞 wu） */
(function assertUniqueWordIds() {
  const seen = Object.create(null);
  WORDS.forEach((w) => {
    if (seen[w.id]) {
      console.error('Duplicate word id:', w.id, seen[w.id], 'vs', w.term);
    }
    seen[w.id] = w.term;
  });
})();

/** 產生卡片插圖 HTML（大粒系統 Emoji；有 photo 就用真實相） */
function wordIllustHtml(word) {
  const badgeIsEmoji = word.badge && /\p{Extended_Pictographic}/u.test(word.badge);
  const badge = word.badge
    ? `<span class="emoji-badge${badgeIsEmoji ? ' emoji-badge-icon' : ''}" aria-hidden="true">${word.badge}</span>`
    : '';
  if (word.photo) {
    return `<span class="emoji-plate" style="--plate:${word.plate || '#122848'}">
    <img class="word-photo" src="${word.photo}" alt="${word.term}" loading="lazy" />
    ${badge}
  </span>`;
  }
  const faceClass = word.emojiDuo ? 'emoji-face emoji-face-duo' : 'emoji-face';
  return `<span class="emoji-plate" style="--plate:${word.plate || '#122848'}">
    <span class="${faceClass}" aria-hidden="true">${word.emoji}</span>
    ${badge}
  </span>`;
}

