#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'js/book-scene-demo.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'book-scene-demo.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
const pageManifest = JSON.parse(fs.readFileSync(path.join(root, 'data/red-series/story-page-hq-manifest.json'), 'utf8'));
assert.match(source, /id: 'balloon'/);
assert.match(source, /id: 'anan'/);
for (const id of ['rb_yusan', 'rb_xin', 'rb_fenguo', 'rb_kuaipao', 'rb_shuijiao', 'rb_huangye', 'rb_yishuhua', 'rb_fengwan', 'rb_xiaoming', 'rb_dongdong']) assert.match(source, new RegExp(`['\"]${id}['\"]`));
assert.match(source, /BOOKS\.push\(\.\.\.RED_BOOKS\)/);
assert.match(source, /kaka-red-book-game-v2/);
assert.match(source, /mode: 'preview'/);
assert.match(source, /scenes: \[0, 1, 2, 3, 4\]/);
assert.match(source, /scene-neutral-preview/);
assert.match(source, /assets\/book-scenes\/red-series-pages-hq\/\$\{title\}-p\$\{/);
assert.match(source, /誰在叫-p\$\{\(page % 2\) \+ 5\}/);
assert.match(source, /小明和氣球.*風跟我玩/);
assert.match(source, /title === '小明和氣球' \|\| title === '風跟我玩'/);
assert.match(source, /真實故事頁・頁面配對待核實/);
assert.equal(pageManifest.books.length, 10);
assert.ok(pageManifest.books.every((book) => book.pages.length >= 2));
const pageAssets = fs.readdirSync(path.join(root, 'assets/book-scenes/red-series-pages-hq'));
assert.equal(pageAssets.length, 30);
assert.ok(pageAssets.includes('小明和氣球-p5.webp'));
assert.ok(pageAssets.includes('風跟我玩-p5.webp'));
assert.ok(pageAssets.includes('誰在叫-p5.webp'));
assert.equal((source.match(/image: 'assets\/book-scenes\//g) || []).length, 6);
for (const term of ['紅氣球', '藍氣球', '黃氣球', '綠氣球', '氣球', '飛走了', '花生', '糖果', '餅乾', '水果', '薯片', '汽水']) assert.ok(source.includes(`word: '${term}'`));
assert.ok((source.match(/distractors:/g) || []).length >= 7);
for (const file of ['balloon-colours-a.jpg', 'balloon-colours-b.jpg', 'balloon-flew-away.jpg', 'anan-snacks.jpg', 'anan-biscuits-fruit.jpg', 'anan-chips-drink.jpg']) assert.ok(fs.existsSync(path.join(root, 'assets/book-scenes', file)));
assert.match(source, /draggable=/);
assert.match(source, /answer-slot/);
assert.match(source, /addEventListener\('drop'/);
assert.match(source, /直接揿正確字詞，就自動放入下一個空格/);
assert.match(html, /每頁答對固定得 2 粒星/);
assert.match(source, /Array\.from\(\{ length: 4 \}/);
assert.match(source, /stars \+= 2/);
assert.doesNotMatch(source, /把詞語放到.*位置/);
assert.match(source, /if \(!heardWhileSelecting\) speak\(word\)/);
assert.match(source, /scene-submit/);
assert.match(html, /js\/speech\.js/);
assert.match(app, /book-scene-demo\.html/);
assert.match(app, /紅輯場景遊戲・12 本書最新版/);
console.log('Book scene demo tests: 9 passed');
