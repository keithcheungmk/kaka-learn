#!/usr/bin/env python3
"""Emit common-sense pack JS files and validate 8–16 漢字 option lengths."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def han(text: str) -> int:
    return len(re.findall(r"[\u4e00-\u9fff]", text))


ERRORS: list[str] = []


def item(id, name, image, wall, ask, correct, wrong, audio):
    for choice in [correct, *wrong]:
        n = han(choice)
        if not 8 <= n <= 16:
            ERRORS.append(f"{id} 選項「{choice}」字數 {n} 要 8–16")
    if len(wrong) != 3:
        ERRORS.append(f"{id} 要 3 個錯選")
    if han(audio) <= han(correct):
        ERRORS.append(f"{id} 錄音稿要長過掣面")
    return {
        "id": id,
        "name": name,
        "image": image,
        "wallLine": wall,
        "ask": ask,
        "correct": correct,
        "wrong": wrong,
        "audio": audio,
    }


def dump_js(var_or_key: str, obj: dict, path: Path, register: bool) -> None:
    body = json.dumps(obj, ensure_ascii=False, indent=2)
    # json uses double quotes; JS files in repo use unquoted keys sometimes, JSON is valid JS
    if register:
        src = (
            f"/** 卡卡常識樂園 · {obj['title']} */\n"
            "window.COMMON_SENSE_PACKS = window.COMMON_SENSE_PACKS || {};\n"
            f"window.COMMON_SENSE_PACKS[{json.dumps(obj['packId'])}] = {body};\n"
        )
    else:
        src = f"/** 卡卡常識樂園目錄 */\nwindow.{var_or_key} = {body};\n"
    path.write_text(src, encoding="utf-8")
    print("wrote", path.relative_to(ROOT), "items", len(obj.get("items") or []))


